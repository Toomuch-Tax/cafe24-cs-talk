// 고객이 답답해하는 신호 (답 없음 항의·반복·재촉)
const FRUSTRATED =
  /답변.{0,8}(없|안\s*(와|오|주))|답장.{0,6}(없|안)|연락.{0,8}(없|안\s*(와|오|주)|좀)|몇\s*번(째)?|계속\s*(문의|연락|기다)|여러\s*번|빨리|언제\s*(연결|답)|왜.{0,10}(안|답)|;;|ㅡㅡ|짜증|화가\s*나|어이없|황당|실망|너무하/;
// 날짜 제약
const DEADLINE = /여행|출국|행사|촬영|결혼식|내일\s*까지|이번\s*주\s*(안|까지|내)|주말\s*(전|까지)|까지\s*(꼭|받아야|필요)|급해|급합|급하/;

export function triage(text: string, category?: string | null): Triage {
  const t = text.slice(0, 3000);
  const hit = TYPES.find((x) => x.re.test(t));
  const signals: string[] = [];
  if (FRUSTRATED.test(t)) signals.push("답답함");
  if (DEADLINE.test(t)) signals.push("날짜 제약");
  const type = hit?.type ?? (category === "defect" ? "불량·오배송·누락" : "일반 문의");
  const urgent = Boolean(hit?.urgent) || category === "defect" || signals.length > 0;
  return { level: urgent ? "urgent" : "normal", type, signals };
}
